using System;
using Content.Client.UserInterface.Controls;
using Content.Shared.SS220.Pinpointer;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.SS220.Pinpointer.UI;

[GenerateTypedNameReferences]
public sealed partial class DnaPinpointerMenu : FancyWindow
{
    public Action<string>? OnAddDna;
    public Action<string>? OnSelectDna;

    public DnaPinpointerMenu()
    {
        RobustXamlLoader.Load(this);

        AddButton.OnPressed += _ =>
        {
            if (!string.IsNullOrWhiteSpace(DnaInput.Text))
            {
                OnAddDna?.Invoke(DnaInput.Text.Trim());
                DnaInput.Text = "";
            }
        };

        DnaInput.OnTextChanged += _ =>
            AddButton.Disabled = string.IsNullOrWhiteSpace(DnaInput.Text);
    }

    public void UpdateState(PinpointerDnaUIState state)
    {
        SavedDnasList.RemoveAllChildren();

        if (state.SavedDnas != null)
        {
            foreach (var dna in state.SavedDnas)
            {
                var isActive = state.ActiveDna == dna;
                var button = CreateDnaButton(dna, isActive);
                if (button != null)
                    SavedDnasList.AddChild(button);
            }
        }
    }

    private Button CreateDnaButton(string dna, bool isActive)
    {
        var button = new Button
        {
            StyleClasses = { "OpenBoth" },
            SetHeight = 30,
            Margin = new Thickness(5, 0, 5, 5),
            HorizontalExpand = true,
        };

        var label = new Label
        {
            Text = dna,
            HorizontalExpand = true,
            HorizontalAlignment = HAlignment.Center,
            Modulate = isActive ? Color.LimeGreen : Color.White,
        };

        button.AddChild(label);
        button.OnPressed += _ => OnSelectDna?.Invoke(dna);

        return button;
    }
}